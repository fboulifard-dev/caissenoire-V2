async function importFines() {
  const batch = db.batch();

  for (const fine of fines) {
    const fineRef = db
      .collection("seasons")
      .doc("2026")
      .collection("fines")
      .doc(fine.id);

    batch.set(fineRef, {
      uid: fine.id,
      playerId: fine.playerId,
      playerFirstName: fine.playerFirstName,
      playerLastName: fine.playerLastName,
      playerNickName: fine.playerNickName,
      comment: fine.comment,
      date : fine.date,
      matchDay: fine.matchDay,
      photo: fine.photo,
      amount: fine.amount,
      ruleId: fine.ruleId,
      ruleLabel: fine.ruleLabel
    });
  }

  await batch.commit();

  console.log(`✅ ${fines.length} amendes importées dans seasons/2026/fines`);
}

